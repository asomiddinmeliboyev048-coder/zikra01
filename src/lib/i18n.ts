export function getCanonicalText(text: string, locale: Locale): string {
  if (locale === "uz") return text;
  for (const [uz, en, ru] of rows) {
    if ((locale === "en" ? en : ru) === text) return uz;
  }
  return text;
}

export function canonicalizeText(text: string): string {
  for (const [uz, en, ru] of rows) {
    if (text === uz || text === en || text === ru) return uz;
  }
  return text;
}
